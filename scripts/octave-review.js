/* Vocal Gym · the octave review list (v0.9.5)
   Writes docs/octave-review.md: every line the octave checks flag (octaveChecks in src/engine/repertoire.js), strongest
   first, for a singer to go through. It lists what the page's "check octave" tag shows, and changes nothing. A flag is a
   question, not a finding: nobody has yet measured how many are real slips. import-repertoire.js calls this when it
   writes the data, and test/repertoire.test.js checks they agree.

   Usage: node scripts/octave-review.js [--check]   (--check: only say whether the file is up to date) */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { octaveChecks, sustainText } from '../src/engine/repertoire.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'data', 'repertoire', 'c');
export const REVIEW = join(ROOT, 'docs', 'octave-review.md');
const CHECK_NAME = { spike: 'one swara far from both neighbours', piece: 'same swaras elsewhere in the piece' };
const TIERS = [
  ['Both checks agree', x => x.checks.length === 2],
  ['One swara far from both neighbours', x => x.checks[0] === 'spike' && x.checks.length === 1],
  ['The same swaras read differently elsewhere in the piece', x => x.checks[0] === 'piece' && x.checks.length === 1]
];
const cellOut = t => '`' + t.replace(/`/g, '') + '`';

export function loadAll() { return readdirSync(DIR).map(f => JSON.parse(readFileSync(join(DIR, f), 'utf8'))).sort((a, b) => a.id.localeCompare(b.id)); }

/* every flag of the repertoire, in the order of the list */
export function allFlags(comps = loadAll()) {
  const flags = [];
  comps.forEach(c => octaveChecks(c.sections).forEach((ls, si) => ls.forEach((found, li) => found.forEach(x => flags.push(Object.assign({ c, si, li, line: c.sections[si].lines[li] }, x))))));
  return flags;
}
export function summary(flags = allFlags()) {
  const lines = new Set(flags.map(f => f.c.id + ':' + f.si + ':' + f.li)), comps = new Set(flags.map(f => f.c.id));
  return { flags: flags.length, lines: lines.size, compositions: comps.size, tiers: TIERS.map(([t, f]) => ({ title: t, n: flags.filter(f).length })) };
}
const secName = (c, si) => { const t = c.sections[si].title; return t ? t.replace(/\s+/g, ' ').trim() : 'Section ' + (si + 1); };
const entry = f => {
  const moved = f.changes.map(x => x.was + ' → ' + x.now).join(', ');
  const cells = Array.from(new Set(f.changes.map(x => x.cell)));
  return '- [ ] **' + f.c.name.replace(/[*_|]/g, ' ').trim() + '** · ' + secName(f.c, f.si) + ', line ' + (f.li + 1) + ', cell ' + cells.map(k => k + 1).join(' and ') + ': ' + moved + '\n' +
    cells.map(k => '  - ' + cellOut(sustainText(f.line.cells[k])) + ' → ' + cellOut(sustainText(f.cells[k]))).join('\n') +
    (f.usually ? '\n  - Elsewhere in the piece, ' + f.times + ' times: ' + cellOut(f.usually) : '') +
    '\n  - `' + f.c.id + '`' + (f.c.url ? ' · [the post](' + f.c.url + ')' : '');
};
export function reviewText(comps = loadAll()) {
  const flags = allFlags(comps), S = summary(flags);
  const out = ['# Octave review list', '',
    'Every line the octave checks flag, strongest evidence first. **A flag is a question, not a finding.** Some of these are real slips in the source, and some are real leaps. Nobody has measured the share yet, so reviewing a sample from each group is the first job.', '',
    'For each one, tick it if the suggestion is right, and note the group. The share of ticks in each group says how far to trust that check. To correct one for yourself, open the composition and use its **check octave** tag; to correct it for everyone, add it to `CONFIRMED_SLIPS` in `scripts/import-repertoire.js`.', '',
    'Generated by `node scripts/octave-review.js`. Do not edit it by hand: ticks here are overwritten by the next import, so keep a copy while reviewing.', '',
    '**' + S.flags + ' suggestions on ' + S.lines + ' lines in ' + S.compositions + ' compositions.**', '',
    '| Group | Suggestions |', '| --- | --- |', ...S.tiers.map(t => '| ' + t.title + ' | ' + t.n + ' |'), '',
    'The checks: ' + Object.entries(CHECK_NAME).map(([k, v]) => '`' + k + '`, ' + v).join('; ') + '.', ''];
  TIERS.forEach(([title, test]) => {
    const list = flags.filter(test);
    out.push('## ' + title + ' (' + list.length + ')', '', list.map(entry).join('\n') || 'None.', '');
  });
  return out.join('\n');
}
export function writeReview() { writeFileSync(REVIEW, reviewText()); }

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    let raw = ''; try { raw = readFileSync(REVIEW, 'utf8').replace(/\r\n/g, '\n'); } catch (e) { /* not written yet */ }
    if (raw !== reviewText()) { console.error('docs/octave-review.md is out of date: run node scripts/octave-review.js'); process.exit(1); }
    console.log('docs/octave-review.md is up to date');
  } else { writeReview(); const S = summary(); console.log('Wrote docs/octave-review.md: ' + S.flags + ' suggestions on ' + S.lines + ' lines in ' + S.compositions + ' compositions; ' + S.tiers.map(t => t.n).join(' / ')); }
}
