/* Vocal Gym · compile data/raga-profiles.json into src/engine/data/profiles.generated.js
   The JSON (about 500 KB) is the source of truth. The engine only needs a small part of it, and
   must not parse JSON at runtime in the browser, so this script keeps what the kalpana generator
   uses and writes it as a plain ES module. The output is deterministic: the same JSON always gives
   the same file, byte for byte, and test/raga-profiles.test.js fails if the committed file is stale.

   Per raga:
     landing, avoidLanding                 pitch classes from kalpanaHints
     nyasa, jiva, alpa, notNyasa           pitch classes from swaraRoles
     janta, dattu                          'suits' | 'neutral' | 'avoid' | 'unknown'
     confidence                            confidence.phrases
     phrases     directionRuleOk && inEngineRange && weight >= 0.15
                 { id, pitches, durs, type, weight, octaveCertain, source }
                 a karvai lengthens the previous swara by one slot
     exceptions  documented direction-rule exceptions (anya swaras, vakra steps), same fields plus
                 anya; used only with kalpana's allowExceptions option
     avoid       entries that name swaras: { pitches, strength }
     gamaka      gamakaRender resolved for the renderer: rules keyed by pitch class, targets as
                 semitone offsets from the swara; ragas without data get the light default
   SOURCES (a second export): { title, url, reliability } for every source a compiled phrase cites.

   Usage: node scripts/compile-profiles.js   (validates the JSON first; exit 1 on errors) */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { mod12 } from '../src/engine/projection.js';
import { parsePhrase, letterMap, engineRagas, validateProfiles, compileGamaka } from './check-raga-profiles.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const PROFILES_JSON = join(root, 'data', 'raga-profiles.json');
export const PROFILES_MODULE = join(root, 'src', 'engine', 'data', 'profiles.generated.js');
export const MIN_WEIGHT = 0.15;

/* Durations of a phrase string: 1 per swara, plus 1 for every karvai that follows it. */
function durations(str) {
  const durs = [];
  for (const tok of str.trim().split(/\s+/)) {
    if (tok === ',') { if (durs.length) durs[durs.length - 1]++; }
    else durs.push(1);
  }
  return durs;
}

/* Swara letters (with optional octave marks) to sorted, distinct pitch classes. */
function pcsOf(raga, letters) {
  const lm = letterMap(raga), out = new Set();
  (letters || []).forEach(x => { const pc = lm[String(x).replace(/['.]$/, '')]; if (pc != null) out.add(mod12(pc)); });
  return Array.from(out).sort((a, b) => a - b);
}

function compilePhrase(raga, id, k, ph) {
  const r = parsePhrase(raga, ph.swaras);
  if (r.error) throw new Error(id + ' phrase ' + k + ': ' + r.error);
  const durs = durations(ph.swaras);
  if (durs.length !== r.pitches.length) throw new Error(id + ' phrase ' + k + ': durations do not match pitches');
  return { id: id + '#' + k, pitches: r.pitches, durs, type: ph.type, weight: ph.weight, octaveCertain: ph.octaveCertain, source: ph.source };
}

/* The compiled table as a plain object, keyed by raga id in sorted order. */
export function compileProfileTable(doc) {
  const E = engineRagas(), table = {};
  Object.keys(doc.ragas).sort().forEach(id => {
    const raga = E[id], p = doc.ragas[id];
    if (!raga) throw new Error('unknown raga id ' + id);
    const roles = p.swaraRoles || {}, hints = p.kalpanaHints || {};
    const phrases = [], exceptions = [];
    (p.phrases || []).forEach((ph, k) => {
      if (!ph.inEngineRange || !(ph.weight >= MIN_WEIGHT)) return;
      if (ph.directionRuleOk) phrases.push(compilePhrase(raga, id, k, ph));
      else exceptions.push(Object.assign(compilePhrase(raga, id, k, ph), { anya: (ph.anyaSwaras || []).slice() }));
    });
    const avoid = [];
    (p.avoid || []).forEach(a => {
      if (a.swaras == null) return;
      const r = parsePhrase(raga, a.swaras);
      if (r.error) throw new Error(id + ' avoid "' + a.swaras + '": ' + r.error);
      avoid.push({ pitches: r.pitches, strength: a.strength });
    });
    table[id] = {
      landing: pcsOf(raga, hints.landingSwaras), avoidLanding: pcsOf(raga, hints.avoidLanding),
      nyasa: pcsOf(raga, roles.nyasa), jiva: pcsOf(raga, roles.jiva), alpa: pcsOf(raga, roles.alpa), notNyasa: pcsOf(raga, roles.notNyasa),
      janta: p.janta, dattu: p.dattu,
      confidence: p.confidence.phrases,
      gamaka: compileGamaka(raga, p.gamakaRender),
      phrases, exceptions, avoid
    };
  });
  return table;
}

/* The generated module's source text. One phrase per line keeps diffs readable. */
export function compileProfiles(doc) {
  const table = compileProfileTable(doc), J = JSON.stringify, lines = [];
  lines.push('/* GENERATED by scripts/compile-profiles.js from data/raga-profiles.json. Do not edit; run npm run profiles. */');
  lines.push('/* Raga profiles for the kalpana generator: schemaVersion ' + doc.schemaVersion + ', data generated ' + doc.generated + '. */');
  lines.push('export default {');
  const ids = Object.keys(table);
  ids.forEach((id, n) => {
    const e = table[id];
    lines.push('  ' + J(id) + ': {');
    lines.push('    landing: ' + J(e.landing) + ', avoidLanding: ' + J(e.avoidLanding) + ',');
    lines.push('    nyasa: ' + J(e.nyasa) + ', jiva: ' + J(e.jiva) + ', alpa: ' + J(e.alpa) + ', notNyasa: ' + J(e.notNyasa) + ',');
    lines.push('    janta: ' + J(e.janta) + ', dattu: ' + J(e.dattu) + ', confidence: ' + J(e.confidence) + ',');
    lines.push('    gamaka: ' + J(e.gamaka) + ',');
    ['phrases', 'exceptions', 'avoid'].forEach(k => {
      if (!e[k].length) { lines.push('    ' + k + ': [],'); return; }
      lines.push('    ' + k + ': [');
      e[k].forEach((x, i) => lines.push('      ' + J(x) + (i < e[k].length - 1 ? ',' : '')));
      lines.push('    ],');
    });
    lines[lines.length - 1] = lines[lines.length - 1].replace(/,$/, '');
    lines.push('  }' + (n < ids.length - 1 ? ',' : ''));
  });
  lines.push('};');
  // the sources the compiled phrases cite, so pages can name them
  const cited = new Set();
  ids.forEach(id => table[id].phrases.concat(table[id].exceptions).forEach(ph => cited.add(ph.source)));
  ids.forEach(id => table[id].gamaka.sources.forEach(s => cited.add(s)));
  const sids = Array.from(cited).sort((a, b) => +a.slice(1) - +b.slice(1));
  lines.push('export const SOURCES = {');
  sids.forEach((s, n) => lines.push('  ' + s + ': ' + J({ title: doc.sources[s].title, url: doc.sources[s].url, reliability: doc.sources[s].reliability }) + (n < sids.length - 1 ? ',' : '')));
  lines.push('};');
  return lines.join('\n') + '\n';
}

/* Validate the JSON, compile it, and write the module. Returns { bytes, ragas, phrases }. */
export function writeProfiles() {
  const doc = JSON.parse(readFileSync(PROFILES_JSON, 'utf8'));
  const errs = validateProfiles(doc);
  if (errs.length) throw new Error('data/raga-profiles.json has ' + errs.length + ' problems (run node scripts/check-raga-profiles.js):\n' + errs.slice(0, 20).join('\n'));
  const src = compileProfiles(doc), table = compileProfileTable(doc);
  mkdirSync(dirname(PROFILES_MODULE), { recursive: true });
  writeFileSync(PROFILES_MODULE, src);
  const ids = Object.keys(table);
  return { bytes: Buffer.byteLength(src), ragas: ids.length, phrases: ids.reduce((s, id) => s + table[id].phrases.length, 0), exceptions: ids.reduce((s, id) => s + table[id].exceptions.length, 0) };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const r = writeProfiles();
    console.log('src/engine/data/profiles.generated.js ' + (r.bytes / 1024).toFixed(0) + ' KB · ' + r.ragas + ' ragas, ' + r.phrases + ' phrases, ' + r.exceptions + ' exceptions');
  } catch (err) { console.error(err.message); process.exit(1); }
}
